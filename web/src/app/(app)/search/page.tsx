"use client";

import type { AtsCompanyDto, SearchQuery, SearchRunDto, SerperCreditInfo } from "@jobpilot/shared";
import { AlertTriangle, Loader2, Plus, Trash2 } from "lucide-react";
import Link from "next/link";
import { useCallback, useEffect, useMemo, useState } from "react";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Switch } from "@/components/ui/switch";
import { Textarea } from "@/components/ui/textarea";
import { api, ApiError, errorMessage } from "@/lib/api";
import { cn } from "@/lib/utils";

const POLL_MS = 1500;
const ACTIVE = new Set(["QUEUED", "RUNNING"]);

const queryKey = (q: SearchQuery) => `${q.q.toLowerCase().replace(/\s+/g, " ").trim()}|${(q.location ?? "").toLowerCase().trim()}`;

function CreditsCard({ credits, planned }: { credits: SerperCreditInfo | null; planned: number }) {
  if (!credits) return null;
  const low = credits.estimatedRemaining < credits.lowWarningThreshold;
  const tooFew = planned > 0 && credits.estimatedRemaining < planned;
  return (
    <div className="flex flex-wrap items-center gap-3 text-sm">
      <span className="text-muted-foreground">Serper credits (estimate):</span>
      <span className={cn("font-medium", (low || tooFew) && "text-destructive")}>
        ≈ {credits.estimatedRemaining.toLocaleString()} left of {credits.total.toLocaleString()}
      </span>
      {!credits.configured && <Badge variant="destructive">SERPER_API_KEY not set</Badge>}
      {(low || tooFew) && (
        <span className="flex items-center gap-1 text-destructive">
          <AlertTriangle className="size-4" />
          {tooFew ? "Fewer credits left than this run needs" : `Below ${credits.lowWarningThreshold}`}
        </span>
      )}
    </div>
  );
}

function QueryEditor({
  run,
  credits,
  enabledCompanies,
  onStarted,
  onDiscard,
}: {
  run: SearchRunDto;
  credits: SerperCreditInfo | null;
  enabledCompanies: number;
  onStarted: (r: SearchRunDto) => void;
  onDiscard: () => void;
}) {
  const [queries, setQueries] = useState<SearchQuery[]>(run.queries);
  const [includeAts, setIncludeAts] = useState(enabledCompanies > 0);
  const [confirming, setConfirming] = useState(false);
  const [starting, setStarting] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const max = credits?.maxQueriesPerRun ?? 15;
  const duplicateIdx = useMemo(() => {
    const seen = new Set<string>();
    const dups = new Set<number>();
    queries.forEach((q, i) => {
      const k = queryKey(q);
      if (seen.has(k)) dups.add(i);
      seen.add(k);
    });
    return dups;
  }, [queries]);
  const valid = queries.filter((q, i) => q.q.trim().length >= 3 && !duplicateIdx.has(i));
  const tooMany = valid.length > max;
  const missingKey = valid.length > 0 && credits?.configured === false;
  const canRun = !tooMany && !missingKey && (valid.length > 0 || includeAts);

  function update(i: number, patch: Partial<SearchQuery>) {
    setConfirming(false);
    setQueries((qs) => qs.map((q, j) => (j === i ? { ...q, ...patch } : q)));
  }

  async function start() {
    setStarting(true);
    setError(null);
    try {
      onStarted(await api<SearchRunDto>(`/search-runs/${run.id}/start`, { method: "POST", body: JSON.stringify({ queries: valid, includeAts }) }));
    } catch (err) {
      setError(errorMessage(err));
      setStarting(false);
      setConfirming(false);
    }
  }

  return (
    <Card>
      <CardHeader>
        <CardTitle>Review queries</CardTitle>
        <CardDescription>
          Generated by {run.queryGenerator === "llm" ? "AI from your profile" : "the fallback generator (AI call failed)"}. Nothing has been sent to Serper
          yet. Edit, remove or add queries, then confirm. Each query uses 1 credit (1 page), at most 2 if Serper needs a retry.
        </CardDescription>
      </CardHeader>
      <CardContent className="space-y-4">
        <div className="space-y-3">
          {queries.map((q, i) => (
            <div key={i} className={cn("grid gap-2 rounded-md border p-3 md:grid-cols-[1fr_16rem_auto]", duplicateIdx.has(i) && "border-destructive bg-destructive/5")}>
              <Textarea value={q.q} rows={2} onChange={(e) => update(i, { q: e.target.value })} className="font-mono text-xs" />
              <div className="space-y-1">
                <Input
                  value={q.location ?? ""}
                  placeholder="No location (e.g. remote)"
                  onChange={(e) => update(i, { location: e.target.value.trim() === "" ? null : e.target.value })}
                />
                {duplicateIdx.has(i) && <p className="text-xs text-destructive">Duplicate, will be skipped</p>}
              </div>
              <Button type="button" variant="ghost" size="icon" aria-label="Remove query" onClick={() => setQueries((qs) => qs.filter((_, j) => j !== i))}>
                <Trash2 />
              </Button>
            </div>
          ))}
          <Button type="button" variant="outline" size="sm" onClick={() => setQueries((qs) => [...qs, { q: "", location: null }])}>
            <Plus /> Add query
          </Button>
        </div>

        <div className="flex items-center gap-3">
          <Switch id="ats" checked={includeAts} onCheckedChange={(v) => setIncludeAts(v)} />
          <Label htmlFor="ats">
            Also read {enabledCompanies} company board{enabledCompanies === 1 ? "" : "s"} from{" "}
            <Link href="/settings" className="underline">
              Settings
            </Link>{" "}
            (free, no credits)
          </Label>
        </div>

        <CreditsCard credits={credits} planned={valid.length} />

        {tooMany && (
          <Alert variant="destructive">
            <AlertDescription>
              {valid.length} queries; the limit is {max} per run. Remove {valid.length - max}.
            </AlertDescription>
          </Alert>
        )}
        {missingKey && (
          <Alert variant="destructive">
            <AlertDescription>Add SERPER_API_KEY to .env and restart the API and worker.</AlertDescription>
          </Alert>
        )}
        {error && (
          <Alert variant="destructive">
            <AlertDescription>{error}</AlertDescription>
          </Alert>
        )}

        <div className="flex flex-wrap items-center gap-2">
          {!confirming ? (
            <Button disabled={!canRun} onClick={() => setConfirming(true)}>
              Run search ({valid.length} {valid.length === 1 ? "query" : "queries"})
            </Button>
          ) : (
            <>
              <Button disabled={starting} onClick={start}>
                {starting ? <Loader2 className="animate-spin" /> : null}
                Confirm: spend up to {valid.length} credit{valid.length === 1 ? "" : "s"}
              </Button>
              <Button variant="ghost" onClick={() => setConfirming(false)}>
                Back
              </Button>
            </>
          )}
          <Button variant="ghost" onClick={onDiscard}>
            Discard &amp; regenerate
          </Button>
        </div>
      </CardContent>
    </Card>
  );
}

function RunProgress({ run }: { run: SearchRunDto }) {
  const active = ACTIVE.has(run.status);
  const stats: [string, number][] = [
    ["Serper calls", run.serperCalls],
    ["Credits used", run.serperCredits],
    ["Results", run.resultsCount],
    ["Duplicate URLs", run.duplicateUrlCount],
    ["Blocked (LinkedIn/Naukri/Indeed)", run.blockedCount],
    ["ATS requests", run.atsCalls],
    ["New jobs", run.newJobsCount],
  ];
  return (
    <Card>
      <CardHeader>
        <div className="flex items-center justify-between gap-2">
          <CardTitle className="flex items-center gap-2">
            {active && <Loader2 className="size-4 animate-spin" />}
            {active ? "Searching…" : run.status === "SUCCEEDED" ? "Search finished" : "Search failed"}
          </CardTitle>
          <Badge variant={run.status === "FAILED" ? "destructive" : active ? "secondary" : "default"}>{run.status}</Badge>
        </div>
        <CardDescription>
          {run.queries.length} queries{run.includeAts ? " + company boards" : ""} · started {run.startedAt ? new Date(run.startedAt).toLocaleTimeString() : "soon"}
        </CardDescription>
      </CardHeader>
      <CardContent className="space-y-4">
        <div className="grid grid-cols-2 gap-3 sm:grid-cols-4">
          {stats.map(([label, value]) => (
            <div key={label} className="rounded-md border p-2">
              <div className="text-xs text-muted-foreground">{label}</div>
              <div className="text-lg font-semibold">{value}</div>
            </div>
          ))}
        </div>
        {run.error && (
          <Alert variant="destructive">
            <AlertDescription>{run.error}</AlertDescription>
          </Alert>
        )}
        <div className="max-h-80 overflow-y-auto rounded-md bg-muted p-3 font-mono text-xs">
          {run.log.map((l, i) => (
            <div key={i} className={cn(l.level === "error" && "text-destructive", l.level === "warn" && "text-amber-600")}>
              <span className="text-muted-foreground">{new Date(l.at).toLocaleTimeString()}</span> {l.msg}
            </div>
          ))}
        </div>
        {!active && (
          <Button asChild>
            <Link href="/jobs">View jobs ({run.newJobsCount} new)</Link>
          </Button>
        )}
      </CardContent>
    </Card>
  );
}

export default function SearchPage() {
  const [run, setRun] = useState<SearchRunDto | null>(null);
  const [credits, setCredits] = useState<SerperCreditInfo | null>(null);
  const [companies, setCompanies] = useState<AtsCompanyDto[]>([]);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [showEditor, setShowEditor] = useState(true);

  const refreshCredits = useCallback(() => api<SerperCreditInfo>("/search-runs/credits").then(setCredits).catch(() => undefined), []);

  useEffect(() => {
    Promise.all([
      api<SearchRunDto>("/search-runs/latest").then(setRun).catch((err) => {
        if (!(err instanceof ApiError && err.status === 404)) setError(errorMessage(err));
      }),
      refreshCredits(),
      api<AtsCompanyDto[]>("/ats-companies").then(setCompanies).catch(() => undefined),
    ]).finally(() => setLoading(false));
  }, [refreshCredits]);

  const runId = run?.id;
  const active = run ? ACTIVE.has(run.status) : false;
  useEffect(() => {
    if (!runId || !active) return;
    const t = setInterval(() => {
      api<SearchRunDto>(`/search-runs/${runId}`)
        .then((r) => {
          setRun(r);
          if (!ACTIVE.has(r.status)) void refreshCredits();
        })
        .catch((err) => setError(errorMessage(err)));
    }, POLL_MS);
    return () => clearInterval(t);
  }, [runId, active, refreshCredits]);

  async function generate() {
    setGenerating(true);
    setError(null);
    try {
      setRun(await api<SearchRunDto>("/search-runs", { method: "POST" }));
      setShowEditor(true);
    } catch (err) {
      const details = err instanceof ApiError && err.code === "PROFILE_INCOMPLETE" ? " Complete your profile first." : "";
      setError(errorMessage(err) + details);
    } finally {
      setGenerating(false);
    }
  }

  const enabledCompanies = companies.filter((c) => c.enabled).length;

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div>
          <h1 className="text-2xl font-semibold">Search</h1>
          <p className="text-sm text-muted-foreground">Queries are generated from your profile and shown here before anything is spent.</p>
        </div>
        {!active && (run?.status !== "DRAFT" || !showEditor) && (
          <Button onClick={generate} disabled={generating}>
            {generating && <Loader2 className="animate-spin" />}
            {generating ? "Generating queries…" : "Generate queries"}
          </Button>
        )}
      </div>

      {error && (
        <Alert variant="destructive">
          <AlertDescription>
            {error}{" "}
            {error.includes("profile") && (
              <Link href="/profile" className="underline">
                Open profile
              </Link>
            )}
          </AlertDescription>
        </Alert>
      )}

      {loading ? (
        <p className="text-sm text-muted-foreground">Loading…</p>
      ) : run?.status === "DRAFT" && showEditor ? (
        <QueryEditor
          key={run.id}
          run={run}
          credits={credits}
          enabledCompanies={enabledCompanies}
          onStarted={setRun}
          onDiscard={() => {
            setShowEditor(false);
            void generate();
          }}
        />
      ) : run && run.status !== "DRAFT" ? (
        <RunProgress run={run} />
      ) : (
        <Card>
          <CardContent className="space-y-3 pt-6">
            <p className="text-sm text-muted-foreground">No search yet. Generate queries to start.</p>
            <CreditsCard credits={credits} planned={0} />
          </CardContent>
        </Card>
      )}
    </div>
  );
}
